export type TranslationKey = keyof typeof translations.ar;

interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey) => string;
  dir: 'rtl' | 'ltr';
  nextLang: () => Lang;
  langLabel: string;
}

const I18nContext = createContext<I18nContextType | null>(null);

const ALL_LANGS: Lang[] = ['ar', 'en', 'fr', 'de', 'es'];

/**
 * `forceLang` pins the language outright. `langs` instead narrows the choice:
 * the standalone Recitation tool offers Arabic and English only, and keeps that
 * choice under its own `storageKey` so opening it never rewrites the board's
 * language on a shared origin.
 */
export function I18nProvider({ children, forceLang, langs = ALL_LANGS, storageKey = 'tajweedoo_lang' }: {
  children: React.ReactNode;
  forceLang?: Lang;
  langs?: Lang[];
  storageKey?: string;
}) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (forceLang) return forceLang;
    const saved = localStorage.getItem(storageKey) as Lang;
    if (saved && langs.includes(saved)) return saved;
    // The browser's language decides the first visit — but only among the ones
    // on offer. A German phone opening an Arabic/English tool gets English,
    // which it can read, rather than a language the tool has no words in.
    const browserLang = navigator.language.split('-')[0] as Lang;
    if (langs.includes(browserLang)) return browserLang;
    return langs.includes('en') ? 'en' : langs[0];
  });

  const setLang = useCallback((l: Lang) => {
    if (forceLang || !langs.includes(l)) return;
    setLangState(l);
    localStorage.setItem(storageKey, l);
  }, [forceLang, langs, storageKey]);

  const t = useCallback((key: TranslationKey): string => {
    return translations[lang][key] || translations.ar[key] || key;
  }, [lang]);

  const dir = lang === 'ar' ? 'rtl' as const : 'ltr' as const;

  const nextLang = useCallback((): Lang => {
    const idx = langs.indexOf(lang);
    return langs[(idx + 1) % langs.length];
  }, [lang, langs]);

  const langLabel = lang === 'ar' ? 'عربي' : lang === 'en' ? 'EN' : lang === 'fr' ? 'FR' : lang === 'de' ? 'DE' : 'ES';

  // During render, not in an effect: children read these names as they render,
  // and a language that arrives one paint late shows Arabic names to an English
  // reader for a frame.
  setDisplayLang(lang);

  useEffect(() => {
    document.documentElement.dir = dir;
    document.documentElement.lang = lang;
  }, [dir, lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir, nextLang, langLabel }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

